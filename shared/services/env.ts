import GLib from "gi://GLib"

// ── Режимы запуска ────────────────────────────────────────────────────────────
// Оба экрана должны запускаться обычным `ags run` в живой сессии, не ломая её.
// Поэтому у каждого есть «боевой» и отладочный режим, и переключаются они по
// окружению, а не по флагу сборки.

/**
 * Экран входа считается боевым, только когда его запустил greetd: сокет к нему
 * живёт в GREETD_SOCK. Без сокета вход всё равно невозможен, так что это же
 * условие включает заглушку аутентификации.
 */
export const GREETER_DEV = GLib.getenv("GREETD_SOCK") === null

/**
 * Блокировщик в отладке рисуется обычным layer-shell окном: настоящий
 * ext-session-lock действительно заблокирует живую сессию, и выйти из неё можно
 * будет только правильным паролем. PAM при этом честный в обоих режимах — он
 * просто проверяет пароль текущего пользователя и ничего не ломает.
 */
export const LOCK_DEV = GLib.getenv("MY_LOCK_DEV") !== null

export const USER = GLib.get_user_name()
